/**
 * WatchPays Payment Gateway Utility
 *
 * Handles MD5 signature generation and order creation for the WatchPays
 * Collection (Payin) API. Server-side only — never import from client components.
 *
 * Official API Specification:
 *   Endpoint: POST https://api.watchpays.com/v1/create
 *   Payload: {
 *     merchant_id: string,
 *     api_key: string,
 *     amount: string (formatted to 2 decimal places),
 *     merchant_order_no: string,
 *     callback_url: string,
 *     signature: string
 *   }
 *
 * Signature Construction Spec:
 *   1. Sort params alphabetically: amount, callback_url, merchant_id, merchant_order_no
 *   2. Concatenate:
 *      amount=${amount}&callback_url=${callbackUrl}&merchant_id=${merchantId}&merchant_order_no=${merchantOrderNo}&key=${apiKey}
 *   3. Generate MD5 hash:
 *      crypto.createHash('md5').update(signStr).digest('hex')
 */

import { createHash } from 'crypto'

const WATCHPAYS_API_BASE = 'https://api.watchpays.com'

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface WatchPaysOrderParams {
  /** INR amount (will be formatted to 2 decimal places) */
  amount: number
  /** Unique order reference generated by our system */
  merchantOrderNo: string
  /** Merchant ID (defaults to WATCHPAYS_MERCHANT_ID env var) */
  merchantId?: string
  /** API Key (defaults to WATCHPAYS_API_KEY env var) */
  apiKey?: string
  /** Callback URL for webhook notifications */
  callbackUrl?: string
}

export interface WatchPaysOrderResult {
  success: boolean
  /** URL to redirect the user to for payment */
  payment_url?: string
  /** WatchPays internal order ID / gateway order number */
  order_no?: string
  /** Human-readable message from the gateway or error description */
  message?: string
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * Generates MD5 signature per WatchPays official specification:
 *   1. Sort params alphabetically: amount, callback_url, merchant_id, merchant_order_no
 *   2. Concatenate:
 *      amount=${amount}&callback_url=${callbackUrl}&merchant_id=${merchantId}&merchant_order_no=${merchantOrderNo}&key=${apiKey}
 *   3. Generate MD5 hash:
 *      crypto.createHash('md5').update(signStr).digest('hex')
 */
export function generateWatchPaysSignature(
  amount: string,
  callbackUrl: string,
  merchantId: string,
  merchantOrderNo: string,
  apiKey: string,
): string {
  const signStr = `amount=${amount}&callback_url=${callbackUrl}&merchant_id=${merchantId}&merchant_order_no=${merchantOrderNo}&key=${apiKey}`
  console.log('[WatchPays] Signature string (key redacted):', `amount=${amount}&callback_url=${callbackUrl}&merchant_id=${merchantId}&merchant_order_no=${merchantOrderNo}&key=****`)
  return createHash('md5').update(signStr, 'utf8').digest('hex')
}

// ---------------------------------------------------------------------------
// API Call
// ---------------------------------------------------------------------------

/**
 * Creates a WatchPays payment order.
 *
 * @returns WatchPaysOrderResult with success flag, payment_url, and order_no on success.
 */
export async function createWatchPaysOrder(
  params: WatchPaysOrderParams,
): Promise<WatchPaysOrderResult> {
  // ── Standardized Credentials (WATCHPAYS_MERCHANT_ID & WATCHPAYS_API_KEY only) ──
  const merchantId = params.merchantId || process.env.WATCHPAYS_MERCHANT_ID
  const apiKey = params.apiKey || process.env.WATCHPAYS_API_KEY
  const { amount, merchantOrderNo } = params

  const siteBase =
    process.env.NEXT_PUBLIC_SITE_URL ||
    (process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : null) ||
    'https://streetexchange.vercel.app'

  const callbackUrl =
    params.callbackUrl ||
    `${siteBase}/api/payment/watchpays/callback`

  if (!merchantId || !apiKey) {
    console.error('[WatchPays] Missing credentials: WATCHPAYS_MERCHANT_ID or WATCHPAYS_API_KEY')
    return {
      success: false,
      message: 'WatchPays gateway unreachable. Please try BondPay.',
    }
  }

  // Format amount to exactly 2 decimal places
  const formattedAmount = Number(amount).toFixed(2)

  // Generate signature per spec
  const signature = generateWatchPaysSignature(
    formattedAmount,
    callbackUrl,
    merchantId,
    merchantOrderNo,
    apiKey,
  )

  // Mandatory JSON payload per official spec
  const payload = {
    merchant_id: merchantId,
    api_key: apiKey,
    amount: formattedAmount,
    merchant_order_no: merchantOrderNo,
    callback_url: callbackUrl,
    signature: signature,
  }

  try {
    console.log('[WatchPays] Sending create order request to https://api.watchpays.com/v1/create:', {
      merchant_id: merchantId,
      amount: formattedAmount,
      merchant_order_no: merchantOrderNo,
      callback_url: callbackUrl,
    })

    // 10-second fetch AbortController timeout
    const response = await fetch(`${WATCHPAYS_API_BASE}/v1/create`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Accept: 'application/json',
      },
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(10_000),
    })

    const rawText = await response.text()
    console.log(`[WatchPays] HTTP response status: ${response.status} ${response.statusText}`)
    console.log('[WatchPays] Raw response body:', rawText)

    let json: Record<string, any>
    try {
      json = JSON.parse(rawText)
    } catch {
      console.error('[WatchPays] Non-JSON response received:', rawText)
      return {
        success: false,
        message: 'WatchPays gateway unreachable. Please try BondPay.',
      }
    }

    if (!response.ok) {
      console.error(`[WatchPays] HTTP error ${response.status}:`, json)
      return {
        success: false,
        message: json?.message || json?.msg || 'WatchPays gateway unreachable. Please try BondPay.',
      }
    }

    // Extract payment URL and order number
    const data = json?.data || json
    const paymentUrl: string | undefined =
      data?.paymentUrl ??
      data?.payment_url ??
      data?.pay_url ??
      data?.url ??
      data?.redirectUrl ??
      data?.redirect_url

    const orderNo: string | undefined =
      data?.orderNo ??
      data?.order_no ??
      data?.orderId ??
      data?.gateway_order_no ??
      data?.gatewayOrderNo ??
      data?.tradeNo ??
      data?.trade_no

    if (!paymentUrl || typeof paymentUrl !== 'string' || !paymentUrl.trim()) {
      console.error('[WatchPays] Missing payment_url in response:', json)
      return {
        success: false,
        message: json?.message || 'WatchPays gateway unreachable. Please try BondPay.',
      }
    }

    return {
      success: true,
      payment_url: paymentUrl.trim(),
      order_no: orderNo ? String(orderNo) : undefined,
      message: json?.message ?? 'Order created successfully.',
    }
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Unknown error'
    console.error('[WatchPays] Network/fetch error (or timeout):', message)
    return {
      success: false,
      message: 'WatchPays gateway unreachable. Please try BondPay.',
    }
  }
}

